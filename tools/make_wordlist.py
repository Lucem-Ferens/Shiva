"""Write src/shiva/wordlist.py from the EFF large wordlist (7776 words, https://www.eff.org/dice).

Usage:  python tools/make_wordlist.py PATH/TO/eff_large_wordlist.txt

The source file is checked against the SHA-256 pinned below before anything is written, so the generated module is always
the same list. The list is ASCII, one `NNNNN<TAB>word` line per word, lowercase; four words contain a hyphen.
"""
from __future__ import annotations

import base64
import hashlib
import sys
import zlib
from pathlib import Path

SOURCE_SHA256 = "addd35536511597a02fa0a9ff1e5284677b8883b83e986e43f15a3db996b903e"
OUT = Path(__file__).resolve().parents[1] / "src" / "shiva" / "wordlist.py"

HEADER = '''"""The EFF large wordlist: 7776 words for passphrases (generated by tools/make_wordlist.py; do not edit by hand).

Source: https://www.eff.org/dice (eff_large_wordlist.txt, SHA-256 {sha}).
The list is copyright the Electronic Frontier Foundation, licensed under the Creative Commons Attribution 4.0
International License (https://creativecommons.org/licenses/by/4.0/); it is shipped unchanged apart from the layout
of this file (the words without their dice numbers, one per line, compressed with zlib and written as base64), and stays
under that licence, not under the licence of the rest of the program. `passgen` checks the decoded words against a pinned
SHA-256 before it uses them.
"""
import base64
import zlib

_DATA = (
'''
FOOTER = ''')

WORDS: tuple[str, ...] = tuple(zlib.decompress(base64.b64decode("".join(_DATA))).decode("ascii").split("\\n"))
'''


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__)
        return 2
    raw = Path(sys.argv[1]).read_bytes()
    digest = hashlib.sha256(raw).hexdigest()
    if digest != SOURCE_SHA256:
        print(f"refused: SHA-256 {digest} differs from the pinned {SOURCE_SHA256}", file=sys.stderr)
        return 1
    words: list[str] = []
    for n, line in enumerate(raw.decode("ascii").split("\n")):
        if not line:
            continue
        dice, word = line.split("\t")
        assert dice.isdigit() and len(dice) == 5 and word.isascii() and word == word.lower() and word, (n, line)
        words.append(word)
    assert len(words) == 7776 and len(set(words)) == 7776
    blob = base64.b64encode(zlib.compress("\n".join(words).encode("ascii"), 9)).decode("ascii")
    body = "".join(f'    "{blob[i:i + 72]}"\n' for i in range(0, len(blob), 72))
    OUT.write_text(HEADER.format(sha=SOURCE_SHA256) + body + FOOTER, encoding="utf-8", newline="\n")
    print(f"wrote {OUT} ({len(words)} words)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
